const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const listeners=new Map();
const target=()=>({dataset:{},attributes:{},addEventListener(name,fn){listeners.set(this.id+':'+name,fn);},setAttribute(name,value){this.attributes[name]=value;},contains(node){return node===this;},focus(){this.focused=true;}});
const button=Object.assign(target(),{id:'button'}),menu=Object.assign(target(),{id:'menu'}),desktop=Object.assign(target(),{id:'desktop'}),doc=Object.assign(target(),{id:'document'});
doc.getElementById=id=>id==='menuBtn'?button:menu;
vm.runInNewContext(fs.readFileSync(path.join(root,'assets/navigation.js'),'utf8'),{document:doc,window:{matchMedia:()=>desktop}});
const emit=(node,type,event={})=>listeners.get(node.id+':'+type)(event);
const open=()=>{emit(button,'click');assert.equal(menu.dataset.open,'true');assert.equal(button.attributes['aria-expanded'],'true');};
const closed=()=>{assert.equal(menu.dataset.open,'false');assert.equal(button.attributes['aria-expanded'],'false');assert.equal(button.attributes['aria-label'],'Open menu');};
closed();open();emit(button,'click');closed();
open();emit(menu,'click',{target:{closest:()=>({})}});closed();
open();emit(doc,'pointerdown',{target:button});assert.equal(menu.dataset.open,'true');emit(doc,'pointerdown',{target:{}});closed();
open();emit(doc,'keydown',{key:'Escape'});closed();assert(button.focused);
open();emit(doc,'focusin',{target:menu});assert.equal(menu.dataset.open,'true');emit(doc,'focusin',{target:{}});closed();
open();emit(desktop,'change');closed();
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(html.includes('aria-controls="menu"')&&html.includes('@media(max-width:1023px)'));
assert(html.includes('assets/catalog.js?v=')&&html.includes('assets/navigation.js?v='));
assert(!fs.readFileSync(path.join(root,'assets/catalog.js'),'utf8').includes('menuBtn'));
console.log('PASS: independent responsive menu, toggle, link/outside/focus/Escape dismissal, resize reset and cache-versioned scripts.');
